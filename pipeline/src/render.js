// Fill the templates with what detect() found and the pinned versions in
// versions.json (ARCH §10.3). Templates use @@NAME@@ placeholders (GitHub's
// own ${{ }} expressions pass through untouched) and @@BEGIN x@@ … @@END x@@
// sections that are kept only when they apply. Output is deterministic: no
// timestamps, sorted inputs, so re-running produces no diff.

import { readFileSync } from 'node:fs';

const TEMPLATES = new URL('../templates/', import.meta.url);
const DEFAULT_ALLOWLIST_DESCRIPTION = 'Committed example files with placeholder values only';

export const loadVersions = () => JSON.parse(readFileSync(new URL('../versions.json', import.meta.url), 'utf8'));
const template = (name) => readFileSync(new URL(name, TEMPLATES), 'utf8');

export const generatedHeader = (versions) =>
  [
    `# Generated by kairo-init ${versions.generator} (Kairo Shield). To change it, edit Kairo's`,
    '# pipeline/ templates or versions.json and re-run kairo-init with --force.',
    '#',
  ].join('\n');

const fill = (text, sections, values) => {
  const out = text
    .replace(/^@@BEGIN (\w+)@@\n([\s\S]*?)^@@END \1@@\n/gm, (_m, name, body) => (sections[name] ? body : ''))
    .replace(/@@([A-Z0-9_]+)@@/g, (m, key) => {
      if (!(key in values)) throw new Error(`template value missing: ${key}`);
      return values[key];
    });
  if (/@@[A-Za-z0-9_ ]+@@/.test(out)) throw new Error('unfilled template marker');
  return out;
};

const action = (versions, key) => {
  const a = versions.actions[key];
  if (!/^[0-9a-f]{40}$/.test(a.sha)) throw new Error(`${a.uses} must be pinned to a full commit SHA`);
  return `${a.uses}@${a.sha} # ${a.tag}`;
};

/** @returns {string} .github/workflows/kairo-shield.yml */
export const renderWorkflow = (detected, versions = loadVersions()) => {
  const projects = detected.npmProjects;
  const buildSteps = [
    ...projects.map((p) => `      - run: npm ci --prefix ${p.dir}`),
    ...projects.filter((p) => p.hasBuild).map((p) => `      - run: npm run build --prefix ${p.dir}`),
  ];
  if (!/^[0-9a-f]{64}$/.test(versions.gitleaks.sha256)) throw new Error('gitleaks sha256 must be pinned');
  return fill(template('kairoShield.yml.tmpl'), { npm: projects.length > 0 }, {
    GENERATED: generatedHeader(versions),
    RUNNER: versions.runner,
    CHECKOUT: action(versions, 'checkout'),
    SETUP_NODE: action(versions, 'setupNode'),
    UPLOAD_ARTIFACT: action(versions, 'uploadArtifact'),
    GITLEAKS_VERSION: versions.gitleaks.version,
    GITLEAKS_SHA256: versions.gitleaks.sha256,
    NODE_VERSION: versions.node,
    NPM_PROJECTS: projects.map((p) => p.dir).join(', '),
    BUILD_STEPS: buildSteps.join('\n'),
  });
};

/**
 * @returns {string} .gitleaks.toml. Allowlist entries come only from the
 * existing config, with their human-written reasons: kairo-init never invents
 * a reason, so it never allowlists anything on its own.
 */
export const renderGitleaks = (detected, versions = loadVersions()) => {
  const entries = detected.gitleaks?.entries ?? [];
  const paths = entries.map((e) => `  # reason: ${e.reason ?? 'TODO: say why this path is safe to skip'}\n  '''${e.regex}''',`);
  return fill(template('gitleaks.toml.tmpl'), { allowlist: entries.length > 0 }, {
    GENERATED: generatedHeader(versions),
    PROJECT_NAME: detected.projectName.replace(/["\\]/g, ''),
    ALLOWLIST_DESCRIPTION: (detected.gitleaks?.description ?? DEFAULT_ALLOWLIST_DESCRIPTION).replace(/["\\]/g, ''),
    ALLOWLIST_PATHS: paths.join('\n'),
  });
};

/** The required status checks to set on `main` by hand (ARCH §10.1). */
export const requiredChecks = (detected) => [
  'secrets',
  ...detected.npmProjects.map((p) => `deps (${p.dir})`),
  ...(detected.npmProjects.length ? ['build'] : []),
];
